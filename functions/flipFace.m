function order=flipFace(nsd,k,N21)
% Reorder the nodes of a face of degree k seen from its two neighboring elements
%
% N21 is the local number of the node of the second face matching the first node of the
% first face, and is only meaningful for the triangular faces of a tetrahedron.

if nsd==2

  % Reverse the two vertices and the k-1 nodes in between
  if k==0
    order=1;
  else
    order=[2,1,(k+1):-1:3];
  end

elseif nsd==3

  % Reflect the triangular face about the axis through the node N21
  switch k
    case 0
      order=1;
    case 1
      Orders=[1,3,2;
              2,1,3;
              3,2,1];
      order=Orders(N21,:);
    case 2
      Orders=[1,3,2,6,5,4;
              2,1,3,4,6,5;
              3,2,1,5,4,6];
      order=Orders(N21,:);
    case 3
      Orders=[1,3,2,9,8,7,6,5,4,10;
              2,1,3,5,4,9,8,7,6,10;
              3,2,1,7,6,5,4,9,8,10];
      order=Orders(N21,:);
    case 4
      Orders=[1,3,2,12,11,10,9,8,7,6,5,4,14,13,15;
              2,1,3,6,5,4,12,11,10,9,8,7,15,14,13;
              3,2,1,9,8,7,6,5,4,12,11,10,13,15,14];
      order=Orders(N21,:);
    case 5
      Orders=[1,3,2,15,14,13,12,11,10,9,8,7,6,5,4,18,17,16,21,20,19;
              2,1,3,7,6,5,4,15,14,13,12,11,10,9,8,20,19,18,17,16,21;
              3,2,1,11,10,9,8,7,6,5,4,15,14,13,12,16,21,20,19,18,17];
      order=Orders(N21,:);
    case 6
      Orders=[1,3,2,18,17,16,15,14,13,12,11,10,9,8,7,6,5,4,22,21,20,19,27,26,25,24,23,28;
              2,1,3,8,7,6,5,4,18,17,16,15,14,13,12,11,10,9,25,24,23,22,21,20,19,27,26,28;
              3,2,1,13,12,11,10,9,8,7,6,5,4,18,17,16,15,14,19,27,26,25,24,23,22,21,20,28];
      order=Orders(N21,:);
    case 7
      Orders=[1,3,2,21,20,19,18,17,16,15,14,13,12,11,10,9,8,7,6,5,4,...
              26,25,24,23,22,33,32,31,30,29,28,27,35,34,36;
              2,1,3,9,8,7,6,5,4,21,20,19,18,17,16,15,14,13,12,11,10,...
              30,29,28,27,26,25,24,23,22,33,32,31,36,35,34;
              3,2,1,15,14,13,12,11,10,9,8,7,6,5,4,21,20,19,18,17,16,...
              22,33,32,31,30,29,28,27,26,25,24,23,34,36,35];
      order=Orders(N21,:);
    case 8
      Orders=[1,3,2,24,23,22,21,20,19,18,17,16,15,14,13,12,11,10,9,8,7,6,5,4,...
              30,29,28,27,26,25,39,38,37,36,35,34,33,32,31,42,41,40,45,44,43;
              2,1,3,10,9,8,7,6,5,4,24,23,22,21,20,19,18,17,16,15,14,13,12,11,...
              35,34,33,32,31,30,29,28,27,26,25,39,38,37,36,44,43,42,41,40,45;
              3,2,1,17,16,15,14,13,12,11,10,9,8,7,6,5,4,24,23,22,21,20,19,18,...
              25,39,38,37,36,35,34,33,32,31,30,29,28,27,26,40,45,44,43,42,41];
      order=Orders(N21,:);
    otherwise
      error('Element not yet implemented');
  end

end

end
